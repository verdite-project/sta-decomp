#!/usr/bin/env python3
"""Hoist game declarations that every unit spells the same way into
include/game/<subsystem>.h.

    tools/headers.py report            write build/headers_report.txt
    tools/headers.py hoist [SUB ...]   hoist (all subsystems by default)
    tools/headers.py hoist --only NAME ...   hoist just these names
    tools/headers.py hoist --singles         also names one unit declares and
                                             another defines (into the definer's header)

A symbol (D_ object or game function) is hoisted when at least two units of
src/game declare it, every declaration (and the definition, for a function)
reads the same once whitespace and parameter names are dropped, and it names
only types the headers already provide. A function spelled differently is
hoisted too when merge_tu.py's unify reconciles the spellings and its own
definition, if it has one, reads the same. It goes into the header of the
subsystem that defines it (the directory of the unit with its body,
INCLUDE_ASM or object definition), else of the subsystem that declares it
most. Units lose their copies and include the headers instead.

`hoist` keeps a unit's change only if its object is byte-for-byte the one it
compiled to before; a unit that differs goes back to its old text (its
declarations stay local) and the round repeats until every object is the old
one. Run `ninja` once before so build/ holds the current objects.
"""
import collections
import re
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import merge_tu as MT     # noqa: E402

ROOT = MT.ROOT
GAME = ROOT / "src/game"
INC = ROOT / "include/game"
BUILD = ROOT / "build"
GAME_NAME = re.compile(r"^(?:(?:D|g[A-Z][A-Za-z0-9]*)_[0-9A-F]{8}|func_[0-9A-F]{8}|[A-Za-z]\w*?_[0-5]_[0-9A-F]{8})$")
KEYWORDS = {"extern", "const", "volatile", "unsigned", "signed", "int", "char", "short", "long", "float",
            "double", "void", "struct", "union", "__attribute__", "aligned"}
OBJDEF = re.compile(r"^(?!extern\b|static\b|typedef\b|return\b)[A-Za-z_][\w \t\*]*?\b((?:D|g[A-Z][A-Za-z0-9]*)_[0-9A-F]{8})\b[ \t]*"
                    r"(?:\[[^\]\n]*\][ \t]*)*(?:=|;)", re.M)
defsig = {}     # function -> (ret, params) of its definition
MARK = "/* Below: generated by tools/headers.py from the units' own declarations. */"
SINGLES = "--singles" in __import__("sys").argv
ASM = re.compile(r"^INCLUDE_ASM\((\w+)\);", re.M)


def units():
    return sorted(p for p in GAME.rglob("*.c"))


def sub_of(p):
    return p.relative_to(GAME).parts[0]


def header_types():
    """Typedef names include/ provides, and the headers that provide them."""
    out = {}
    for h in sorted((ROOT / "include").rglob("*.h")):
        t = h.read_text()
        for m in list(MT.TYPEDEF.finditer(t)) + list(MT.FPTYPEDEF.finditer(t)):
            out[m.group(1)] = h
        for m in re.finditer(r"^typedef\b[^;{]*\b(\w+)\s*;", t, re.M):
            out[m.group(1)] = h
    return out


def strip_comments(t):
    return re.sub(r"/\*.*?\*/", lambda m: re.sub(r"[^\n]", " ", m.group(0)), t, flags=re.S)


def decls(text):
    """(kind, name, key, text, start, end) for every top-level extern object
    and prototype of a game name."""
    clean = strip_comments(text)
    out = []
    for m in MT.EXTERN.finditer(clean):
        name = m.group(3)
        if GAME_NAME.match(name):
            key = re.sub(r"\s+", " ", m.group(0).strip())
            for k, v in MT.ALIAS_T.items():
                key = re.sub(rf"\b{k}\b", v, key)
            key = re.sub(r"\s*\*\s*", "*", key)
            out.append(("obj", name, key, text[m.start():m._b], m.start(), m._b))
    for m in MT.PROTO.finditer(clean):
        name = m.group(2)
        if GAME_NAME.match(name) and m.group(1).strip() not in MT.CONTROL:
            out.append(("fn", name, MT.sig_key(m.group(1).replace("extern", ""), m.group(3)),
                        text[m.start():m.end()], m.start(), m.end()))
    return out


def inventory():
    files = {p: p.read_text() for p in units()}
    seen = collections.defaultdict(list)    # name -> [(path, kind, key, text)]
    owner = {}
    defkey = {}
    defsig.clear()
    for p, t in files.items():
        clean = strip_comments(t)
        for kind, name, key, txt, a, b in decls(t):
            seen[name].append((p, kind, key, txt))
        for m in MT.DEFN_ANY.finditer(clean):
            if GAME_NAME.match(m.group(2)) and m.group(1).strip() not in MT.CONTROL:
                owner[m.group(2)] = p
                defkey[m.group(2)] = MT.sig_key(m.group(1), m.group(3))
                defsig[m.group(2)] = (m.group(1), m.group(3))
        for m in ASM.finditer(clean):
            owner[m.group(1)] = p
        for m in OBJDEF.finditer(clean):
            owner.setdefault(m.group(1), p)
    return files, seen, owner, defkey


def classify(seen, owner, defkey, types, defsig={}):
    """name -> (status, detail)."""
    out = {}
    for name, ds in seen.items():
        keys = {d[2] for d in ds}
        kinds = {d[1] for d in ds}
        users = {d[0] for d in ds}
        if len(kinds) > 1:
            out[name] = ("conflict", "object and function")
            continue
        if name in defkey and kinds == {"fn"}:
            keys.add(defkey[name])
        text = None
        if len(keys) > 1:
            u = unified(name, ds, defsig.get(name)) if kinds == {"fn"} else None
            if not u:
                out[name] = ("conflict", " | ".join(sorted(map(str, keys))))
                continue
            text = u
        # --singles: one unit declares it and another defines it: the
        # declaration goes to the definer's header too (the definer then
        # sees it, so the two must agree)
        if len(users) < 2 and not (SINGLES and name in owner and owner[name] not in users):
            out[name] = ("single", "")
            continue
        status = "unify" if text else "agree"
        text = text or ds[0][3]
        if "{" in text:
            out[name] = ("local-type", "anonymous struct")
            continue
        words = set(re.findall(r"\b[A-Za-z_]\w*\b", re.sub(r"\b" + name + r"\b", "", text)))
        words -= KEYWORDS
        words = {w for w in words if not re.fullmatch(r"[a-z_]\w*", w) or w in types}
        missing = sorted(w for w in words if w not in types)
        if missing:
            out[name] = ("local-type", " ".join(missing))
            continue
        out[name] = (status, text if status == "unify" else "")
    return out


def unified(name, ds, defn):
    """One prototype for differing spellings (tools/merge_tu.py's rules:
    pointers become void *, same-register integers agree), or None."""
    sigs = []
    for d in ds:
        m = MT.PROTO.match(d[3].strip() + "\n")
        if not m:
            return None
        sigs.append((m.group(1).replace("extern", ""), m.group(3)))
    if defn:
        sigs.append(defn)
    u = MT.unify(sigs)
    if not u:
        return None
    ret, params = u
    if defn and MT.sig_key(*defn) != (MT.norm(ret), tuple(params)):
        return None         # the definition's own prototype would conflict
    return f"{ret} {name}({', '.join(params) or 'void'});"


def home(name, seen, owner):
    if name in owner:
        return sub_of(owner[name])
    c = collections.Counter(sub_of(d[0]) for d in seen[name])
    return sorted(c.items(), key=lambda kv: (-kv[1], kv[0]))[0][0]


def report():
    files, seen, owner, defkey = inventory()
    cls = classify(seen, owner, defkey, header_types(), defsig)
    by = collections.defaultdict(list)
    for n, (s, d) in cls.items():
        by[s].append((n, d, len({x[0] for x in seen[n]})))
    out = []
    for s in ("agree", "unify", "conflict", "local-type", "single"):
        out.append(f"## {s}: {len(by[s])}")
        for n, d, k in sorted(by[s], key=lambda x: (-x[2], x[0])):
            out.append(f"{n}\t{k} units\t{d}")
    (BUILD / "headers_report.txt").write_text("\n".join(out) + "\n")
    for s in ("agree", "unify", "conflict", "local-type", "single"):
        print(s, len(by[s]))


def obj(p):
    return BUILD / (str(p.relative_to(ROOT)) + ".o")


def read_header(sub):
    """(hand-written part, {name: generated declaration})."""
    h = INC / f"{sub}.h"
    if not h.exists():
        g = f"GAME_{sub.upper()}_H"
        return f"#ifndef {g}\n#define {g}\n\n#include \"common.h\"\n", {}
    t = h.read_text()
    if MARK not in t:
        return t[:t.rindex("#endif")].rstrip() + "\n", {}
    hand, gen = t.split(MARK, 1)
    return hand.rstrip() + "\n", {d[1]: d[3].strip() for d in decls(gen)}


def write_headers(plan, types):
    """plan: sub -> {name: decl text}, below each header's hand-written part."""
    INC.mkdir(exist_ok=True)
    for sub, names in plan.items():
        hand, _ = read_header(sub)
        need = set()
        for txt in names.values():
            for w in re.findall(r"\b[A-Za-z_]\w*\b", txt):
                if w in types and types[w].name not in ("types.h", "common.h") and types[w] != INC / f"{sub}.h":
                    need.add(types[w].relative_to(ROOT / "include").as_posix())
        need = [x for x in sorted(need) if f'"{x}"' not in hand]
        objs = sorted(n for n, t in names.items() if not t.rstrip().endswith(");"))
        fns = sorted(n for n in names if n not in objs)
        lines = [hand.rstrip(), "", MARK] + [f'#include "{x}"' for x in need]
        if objs:
            lines += [""] + [names[n].strip() for n in objs]
        if fns:
            lines += [""] + [names[n].strip() for n in fns]
        lines += ["", "#endif", ""]
        (INC / f"{sub}.h").write_text("\n".join(lines))


def spell(seen, name):
    """The declaration to put in a header: the most common spelling."""
    c = collections.Counter(re.sub(r"[ \t]+", " ", d[3].strip()) for d in seen[name])
    t = c.most_common(1)[0][0]
    if not t.startswith("extern") and t.rstrip().endswith(");"):
        return t
    return t if t.startswith("extern") else "extern " + t


def rewrite(text, names, include_lines):
    """Drop the declarations of names, add the includes after the last
    existing #include (or at the top)."""
    spans = [(a, b) for kind, n, key, txt, a, b in decls(text) if n in names]
    for a, b in sorted(spans, reverse=True):
        text = text[:a] + text[b:]
    have = set(re.findall(r'^#include\s+"([^"]+)"', text, re.M))
    add = [f'#include "{h}"\n' for h in include_lines if h not in have]
    if add:
        ms = list(MT.INCLUDE.finditer(text))
        at = ms[-1].end() if ms else 0
        text = text[:at] + "".join(add) + text[at:]
    return text


def same(a, b):
    from struct_views import same as sv
    return sv(a, b)


def hoist(subs, only=None):
    files, seen, owner, defkey = inventory()
    types = header_types()
    cls = classify(seen, owner, defkey, types, defsig)
    banned = set()
    tried = set()
    subs_all = sorted({sub_of(p) for p in files} | {h.stem for h in INC.glob("*.h")} if INC.exists() else
                      {sub_of(p) for p in files})
    # what earlier runs hoisted stays; units that still declare it keep their copy
    kept = {sub: read_header(sub)[1] for sub in subs_all}
    old = {n for ns in kept.values() for n in ns}
    snap = BUILD / "headers_snap"
    if snap.exists():
        shutil.rmtree(snap)
    for p in files:
        o = obj(p)
        if not o.exists():
            sys.exit(f"{o} missing: run ninja first")
        d = snap / o.relative_to(BUILD)
        d.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(o, d)
    headers = {h: h.read_text() for h in INC.glob("*.h")} if INC.exists() else {}
    while True:
        plan = collections.defaultdict(dict)
        for sub, ns in kept.items():
            if ns:
                plan[sub].update(ns)
        for n, (s, u) in cls.items():
            if s in ("agree", "unify") and n not in banned and n not in old and (not only or n in only):
                sub = home(n, seen, owner)
                if not subs or sub in subs:
                    plan[sub][n] = u if s == "unify" else spell(seen, n)
        write_headers(plan, types)
        where = {n: sub for sub, ns in plan.items() for n in ns}
        changed = {}
        for p, t in files.items():
            mine = ({d[1] for d in decls(t)} & set(where)) - old
            if not mine:
                continue
            inc = sorted({f"game/{where[n]}.h" for n in mine})
            changed[p] = rewrite(t, mine, inc)
        for p, t in changed.items():
            p.write_text(t)
        subprocess.run([str(ROOT / ".venv/bin/python"), "tools/gen_ninja.py"], cwd=ROOT,
                       stdout=subprocess.DEVNULL, check=True)
        for p in changed:
            obj(p).unlink(missing_ok=True)     # a failed compile must not leave the old object
        subprocess.run(["ninja", "-k", "0"] + [str(obj(p).relative_to(ROOT)) for p in changed],
                       cwd=ROOT, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        bad = [p for p in changed
               if not obj(p).exists() or not same(obj(p).read_bytes(), (snap / obj(p).relative_to(BUILD)).read_bytes())]
        print(f"{sum(len(v) for v in plan.values())} hoisted, {len(changed)} units, {len(bad)} differ")
        if not bad:
            break
        # the names a differing unit hoisted are kept local everywhere: first
        # only the unified ones, then (a unit that differs again) all of them
        for p in bad:
            mine = {d[1] for d in decls(files[p])} & set(where)
            uni = {n for n in mine if cls[n][0] == "unify"}
            banned |= uni if uni and p not in tried else mine
            tried.add(p)
        for p, t in files.items():
            p.write_text(t)
        for h in INC.glob("*.h"):
            if h in headers:
                h.write_text(headers[h])
            else:
                h.unlink()
    shutil.rmtree(snap)


def main():
    if len(sys.argv) < 2 or sys.argv[1] not in ("report", "hoist"):
        sys.exit(__doc__)
    if sys.argv[1] == "report":
        report()
    else:
        if sys.argv[2:3] == ["--only"]:
            hoist(set(), set(sys.argv[3:]))
        else:
            hoist({a for a in sys.argv[2:] if not a.startswith("--")})


if __name__ == "__main__":
    main()
