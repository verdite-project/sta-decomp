#!/usr/bin/env python3
"""Move data objects from the data-only units into the code unit that uses them.

    tools/move_data.py [--section bss|data|rodata]            plan
    tools/move_data.py [--section ...] --apply [src/game/func_X.c ...] [--limit N]

.data and .rodata (initialised): the definition is rebuilt from splat's
per-unit file in the owner's declared type (tools/data_to_c.py's define();
a candidate whose bytes do not fit that type stays), in address order, and
each candidate owner is compiled first and kept only if tools/match.py
still matches it (CodeWarrior folds values it can see into the code). The
remainders are regenerated by data_to_c.py's unit_text(). The owner must
have no section of that name yet (a CodeWarrior unit's jump tables are in
its .rodata).

An object of src/game/data/bss_*.c that exactly one CodeWarrior game unit
refers to (by name, or through a field alias in config/data_aliases.txt) is
defined there instead, in the type that unit declares it with. A unit's
objects must be consecutive in the .bss (a unit's section is one stretch),
the unit must have no .bss yet, and the runs must come in the units' .text
order (one link order for every section): the longest such sequence is taken.
Objects of 8 bytes or less stay (a game unit would put them in .sbss).

The moved run is written from the top down (CodeWarrior writes uninitialised
objects in reverse), each object aligned as tools/data_to_c.py aligns them,
the first carrying the run's largest alignment (a rigid stretch). The
data-only unit is split around what moved, each remainder a unit of its own
(the unit's file if it starts where the unit did, else <name>_<ADDR>.c), and
config/data_aliases.txt regrouped by the unit each field's object is now in.

Data units are found by their header comment (`/* bss_XXXXXXXX: ...`), not
their file name. A run is kept only where link order can place the owner's
section (link_fits).

After --apply: tools/match.py diff for every touched owner; add the owner's
and the remainders' subsegments to config/sta.jp.yaml and the remainders to
config/link_order.jp.txt (data-only units move to agree with their
neighbours); rm -rf asm, ./build.sh, ninja shift. tools/carve.py cannot place
the game units at the moment, so it does not regenerate these.
"""
import bisect
import collections
import glob
import re
import sys
from pathlib import Path

from elftools.elf.elffile import ELFFile
sys.path.insert(0, str(Path(__file__).resolve().parent))
from names import is_func  # noqa: E402


ROOT = Path(__file__).resolve().parent.parent
ALIASES = ROOT / "config/data_aliases.txt"
DEF = re.compile(r"^(?P<decl>[^;/\n]*?\b(?P<name>(?:D|g[A-Z][A-Za-z0-9]*)_[0-9A-F]{8})\b[^;/\n]*);(?P<note>.*)$", re.M)
EXTERN = re.compile(r"^\s*extern\s+(?P<type>(?:(?:volatile|const|unsigned|signed|struct)\s+)*\w+)\s*(?P<ptr>\**)\s*"
                    r"(?P<name>\w+)\s*(?P<dim>\[[^\]]*\])?\s*"
                    r"(?P<attr>__attribute__\(\(\w+(?:\([^()]*\))?\)\)\s*)?;[^\n]*\n?", re.M)
ESZ = {"s8": 1, "u8": 1, "char": 1, "s16": 2, "u16": 2, "s32": 4, "u32": 4, "int": 4,
       "f32": 4, "float": 4, "s64": 8, "u64": 8, "f64": 8, "double": 8}
natural = lambda n: 4 if n <= 4 else 8 if n < 16 else 16


def sizes():
    """name -> (addr, size) of the globals carve lists."""
    out = {}
    for line in (ROOT / "config/symbol_addrs.carve.txt").read_text().splitlines():
        m = re.match(r"(\w+)\s*=\s*0x([0-9A-Fa-f]+);.*size:0x([0-9A-Fa-f]+)", line)
        if m:
            out[m.group(1)] = (int(m.group(2), 16), int(m.group(3), 16))
    return out


def aliases():
    """field name -> object name, from config/data_aliases.txt."""
    out = {}
    for m in re.finditer(r"^(\w+) = (\w+) \+ 0x([0-9A-F]+);", ALIASES.read_text(), re.M):
        out[m.group(1)] = m.group(2)
    return out


def users(names, alias):
    """object name -> set of object files that refer to it."""
    out = collections.defaultdict(set)
    files = glob.glob(str(ROOT / "build/src/**/*.o"), recursive=True) + glob.glob(str(ROOT / "build/asm/**/*.o"), recursive=True)
    for o in files:
        if "/build/src/game/data/" in o or "/build/asm/data/" in o:
            continue    # the data units themselves, and stale asm data objects
        rel = str(Path(o).relative_to(ROOT / "build"))[:-2]
        if rel.startswith(("src/", "asm/")) and not (ROOT / rel).exists():
            continue    # a stale object of a source merged away, removed or resplit
        with open(o, "rb") as f:
            for s in ELFFile(f).get_section_by_name(".symtab").iter_symbols():
                if s["st_shndx"] == "SHN_UNDEF" and s.name:
                    n = alias.get(s.name, s.name)
                    if n in names:
                        out[n].add(str(Path(o).relative_to(ROOT / "build"))[:-2])
    return out


def has_bss(src):
    with open(ROOT / "build" / (src + ".o"), "rb") as f:
        return any(s.name in (".bss", ".sbss") and s["sh_size"] for s in ELFFile(f).iter_sections())


def type_size(t, ptr, text):
    """Size of one element of an extern's type, or None if unknown here."""
    if ptr:
        return 4
    if t in ESZ:
        return ESZ[t]
    sys.path.insert(0, str(ROOT / "tools"))
    import data_to_c
    sc = data_to_c.struct_scalar(t)
    if sc:
        return ESZ[sc[0]] * sc[1]
    # a struct typedef in the owner itself whose members are all scalars
    m = re.search(r"typedef\s+struct\s*\w*\s*\{([^{}]*)\}\s*%s\s*;" % re.escape(t), text)
    if m:
        n = 0
        for d in m.group(1).split(";"):
            d = d.strip()
            if not d:
                continue
            mm = re.fullmatch(r"(\w+)\s+([\w\s,\[\]]+)", d)
            if not mm or mm.group(1) not in ESZ:
                return None
            for v in mm.group(2).split(","):
                k = 1
                for dim in re.findall(r"\[([^\]]+)\]", v):
                    k *= int(dim, 0)
                n += k * ESZ[mm.group(1)]
        return n or None
    return None


def data_units(kind):
    """src/game/data units of a section kind (from the header comment
    `/* <kind>_XXXXXXXX: ...`; the file names are free)."""
    out = []
    for p in sorted(glob.glob(str(ROOT / "src/game/data/*.c"))):
        m = re.search(r"^/\* (bss|data|rodata)_[0-9A-F]{8}\b", Path(p).read_text(), re.M)
        if m and m.group(1) == kind:
            out.append(p)
    return out


def unit_start(unit):
    """The address a data unit's header comment gives."""
    m = re.search(r"^/\* \w+?_([0-9A-F]{8})\b", (ROOT / unit).read_text(), re.M)
    return int(m.group(1), 16)


def remainder_path(unit, first, start):
    """Where a remainder of data unit `unit` (which started at `first`)
    starting at `start` goes: the unit's own file if it starts where the unit
    did, else <stem>_<ADDR>.c."""
    u = ROOT / unit
    stem = re.sub(r"_[0-9A-F]{8}$", "", u.stem)
    return u if first == start else u.with_name(f"{stem}_{start:08X}.c")


def link_fits(sec, own, start, end):
    """Whether own's `sec` can hold [start, end): in link order it must come
    after the unit (not a data-only one, which can move) whose subsegment
    holds the bytes before, and before the one after."""
    ents = []
    for l in (ROOT / "config/sta.jp.yaml").read_text().split("\n"):
        r = re.match(r"\s*- \[0x([0-9A-F]+), (\S+), (\S+)\]$", l)
        d = None if r else re.match(r"\s*- \{.*type: (\S+), vram: 0x([0-9A-F]+), name: (\S+) \}$", l)
        if r and r.group(2) == sec:
            ents.append((int(r.group(1), 16) + 0x100000, r.group(3)))
        elif d and d.group(1) == sec:
            ents.append((int(d.group(2), 16), d.group(3)))
    link = [l.strip() for l in (ROOT / "config/link_order.jp.txt").read_text().split("\n")]
    pos = {re.sub(r"^src/|\.[cs]$", "", l): i for i, l in enumerate(link)}
    me = pos[own[len("src/"):-len(".c")]]
    fixed = [(a, n) for a, n in ents if n in pos and not n.startswith("game/data/") and pos[n] != me]
    before = [n for a, n in fixed if a < start]
    after = [n for a, n in fixed if a >= end]
    return (not before or pos[before[-1]] < me) and (not after or me < pos[after[0]])


def plan():
    sz = sizes()
    alias = aliases()
    units = {}      # object name -> data unit path
    lines = {}      # object name -> its definition line
    for p in data_units("bss"):
        for m in DEF.finditer(Path(p).read_text()):
            units[m.group("name")] = str(Path(p).relative_to(ROOT))
            lines[m.group("name")] = m.group(0)
    us = users(set(units), alias)
    objs = sorted((sz[n][0], n) for n in units if n in sz)
    # runs of consecutive objects with one owner
    runs, cur = [], None
    for a, n in objs:
        own = None
        if len(us[n]) == 1:
            o = next(iter(us[n]))
            if o.startswith("src/game/") and not o.startswith("src/game/ee/") and o.endswith(".c"):
                own = o
        if own and sz[n][1] > 8 and cur and cur[0] == own and cur[1][-1][1] + sz[cur[1][-1][2]][1] == a:
            cur[1].append((a, a, n))
            continue
        if cur:
            runs.append(cur)
        cur = (own, [(a, a, n)]) if own and sz[n][1] > 8 else None
    if cur:
        runs.append(cur)
    # one run per owner, owner without .bss, a known type for every object
    count = collections.Counter(o for o, _ in runs)
    ok = []
    for own, objs_ in runs:
        if count[own] != 1 or has_bss(own):
            continue
        last = objs_[-1][2]
        if not link_fits(".bss", own, objs_[0][0], sz[last][0] + sz[last][1]):
            print(f"{own}: its .bss would be out of link order, stays")
            continue
        text = (ROOT / own).read_text()
        good = True
        for _, a, n in objs_:
            ms = [m for m in EXTERN.finditer(text) if m.group("name") == n]
            if len(ms) != 1:
                good = False
                break
            m = ms[0]
            es = type_size(m.group("type").split()[-1], m.group("ptr"), text)
            # an array declaration takes any multiple; a scalar one only its own size
            if es is None or sz[n][1] % es or (m.group("dim") is None and sz[n][1] != es):
                good = False
                break
        if good:
            ok.append((own, [x[2] for x in objs_]))
    # in .text order: the longest increasing run of owner addresses
    order = {l.strip(): i for i, l in enumerate((ROOT / "config/link_order.jp.txt").read_text().splitlines())}
    key = lambda o: order[o]     # link order is .text order
    ok.sort(key=lambda r: sz[r[1][0]][0])
    tails, prev, idx = [], [None] * len(ok), []
    for i, (own, _) in enumerate(ok):
        k = key(own)
        j = bisect.bisect_left([key(ok[t][0]) for t in idx], k)
        if j > 0:
            prev[i] = idx[j - 1]
        if j == len(idx):
            idx.append(i)
        else:
            idx[j] = i
    chosen, i = [], idx[-1] if idx else None
    while i is not None:
        chosen.append(ok[i])
        i = prev[i]
    return list(reversed(chosen)), sz, alias, units, lines


def owner_text(own, names, sz):
    """The owner's source with its externs for `names` turned into definitions."""
    text = (ROOT / own).read_text()
    defs = []
    start = sz[names[0]][0]
    wants = []
    for n in names:
        a, size = sz[n]
        wants.append(min(natural(size), a & -a, start & -start))
    wants[0] = max(wants)
    first = None
    for n, want in zip(names, wants):
        m = next(m for m in EXTERN.finditer(text) if m.group("name") == n)
        t, ptr, dim = m.group("type"), m.group("ptr"), m.group("dim")
        es = type_size(t.split()[-1], ptr, text)
        cnt = sz[n][1] // es
        d = f"{t} {ptr}{n}[{cnt:#x}]" if dim is not None else f"{t} {ptr}{n}"
        if want != natural(sz[n][1]):
            d += f" __attribute__((aligned({want})))"
        defs.append(d + ";")
        first = m.start() if first is None else min(first, m.start())
    for n in names:
        m = next(m for m in EXTERN.finditer(text) if m.group("name") == n)
        text = text[:m.start()] + text[m.end():]
        if m.start() < first:
            first -= m.end() - m.start()
    block = "/* .bss, from the top down (CodeWarrior writes it in reverse) */\n" + "\n".join(reversed(defs)) + "\n"
    return text[:first] + block + text[first:]


def write_units(moved, sz, units, lines):
    """Rewrite the bss data-only units without the moved objects, split into
    contiguous remainders."""
    by_unit = collections.defaultdict(list)
    for n, u in units.items():
        if n not in moved:
            by_unit[u].append(n)
    for u in {units[n] for n in moved}:
        rest = sorted(by_unit[u], key=lambda n: sz[n][0])
        first = unit_start(u)
        (ROOT / u).unlink()
        parts, cur = [], []
        for n in rest:
            if cur and sz[cur[-1]][0] + sz[cur[-1]][1] != sz[n][0]:
                parts.append(cur)
                cur = []
            cur.append(n)
        if cur:
            parts.append(cur)
        for part in parts:
            start = sz[part[0]][0]
            wants = [min(natural(sz[n][1]), sz[n][0] & -sz[n][0], start & -start) for n in part]
            wants[0] = max(wants)
            out = []
            for n, want in zip(part, wants):
                line = lines[n]
                line = re.sub(r"\s*__attribute__\(\(aligned\(\d+\)\)\)", "", line)
                if want != natural(sz[n][1]):
                    line = line.replace(";", f" __attribute__((aligned({want})));", 1)
                out.append(line)
            stem = f"bss_{start:08X}"
            head = ['#include "common.h"', "",
                    f"/* {stem}: the game's .bss from 0x{start:08X}, defined from the top down",
                    "   (CodeWarrior writes uninitialised objects in reverse order). */", ""]
            remainder_path(u, first, start).write_text("\n".join(head + out[::-1]) + "\n")


def regroup_aliases(sz):
    """config/data_aliases.txt grouped by the unit each field's object is in."""
    where = {}
    for p in glob.glob(str(ROOT / "src/game/**/*.c"), recursive=True):
        for m in DEF.finditer(Path(p).read_text()):
            where.setdefault(m.group("name"), Path(p).stem)
    groups = collections.defaultdict(list)
    for m in re.finditer(r"^(\w+) = (\w+) \+ 0x([0-9A-F]+);", ALIASES.read_text(), re.M):
        groups[where.get(m.group(2), "?")].append(m.group(0))
    head = ("/* Names code uses inside a data object, for ld: written by\n"
            "   tools/data_to_c.py, one block per unit. */\n")
    ALIASES.write_text(head + "".join(f"/* {g} */\n" + "\n".join(v) + "\n" for g, v in sorted(groups.items())))


SEC = {"data": ".data", "rodata": ".rodata"}


def has_sec(src, sec):
    with open(ROOT / "build" / (src + ".o"), "rb") as f:
        return any(s.name in (sec, ".s" + sec[1:]) and s["sh_size"] for s in ELFFile(f).iter_sections())


def plan_init(kind):
    """Like plan(), for initialised data: [(owner, [names])] and the labels."""
    sys.path.insert(0, str(ROOT / "tools"))
    import data_to_c
    sz = sizes()
    alias = aliases()
    labels, unit_of = {}, {}
    for p in data_units(kind):
        asm = ROOT / "asm/data/game/data" / f"{Path(p).stem}.{kind}.s"
        if not asm.exists():
            continue
        for lab in data_to_c.parse(asm):
            labels[lab[0]] = (lab, asm)
            unit_of[lab[0]] = str(Path(p).relative_to(ROOT))
    us = users(set(labels), alias)
    order = sorted((labels[n][0][1], n) for n in labels)
    runs, cur = [], None
    for a, n in order:
        own = None
        size = sz.get(n, (0, 0))[1]
        if len(us[n]) == 1:
            o = next(iter(us[n]))
            if o.startswith("src/game/") and not o.startswith("src/game/ee/") and o.endswith(".c"):
                own = o
        if own and size > 8 and cur and cur[0] == own and unit_of[cur[1][-1]] == unit_of[n] \
                and order.index((a, n)) == order.index((labels[cur[1][-1]][0][1], cur[1][-1])) + 1:
            cur[1].append(n)
            continue
        if cur:
            runs.append(cur)
        cur = (own, [n]) if own and size > 8 else None
    if cur:
        runs.append(cur)
    count = collections.Counter(o for o, _ in runs)
    runs = [r for r in runs if count[r[0]] == 1 and not has_sec(r[0], SEC[kind])]
    keep = []
    for own, names in runs:
        if link_fits(SEC[kind], own, sz[names[0]][0], sz[names[-1]][0] + sz[names[-1]][1]):
            keep.append((own, names))
        else:
            print(f"{own}: its {SEC[kind]} would be out of link order, stays")
    runs = keep
    return runs, sz, labels, unit_of


LOCAL_STRUCT = re.compile(r"typedef\s+struct\s*\w*\s*\{([^{}]*)\}\s*(\w+)\s*"
                          r"(?:__attribute__\(\(\w+(?:\([^()]*\))?\)\)\s*)?;")


def local_structs(text):
    """{name: (scalar type, count)}: the owner's own structs whose members
    share one scalar type (data_to_c.py knows only the headers')."""
    out = {}
    for m in LOCAL_STRUCT.finditer(text):
        ts, n = set(), 0
        for d in m.group(1).split(";"):
            d = d.strip()
            if not d:
                continue
            mm = re.fullmatch(r"(\w+)\s+([\w\s,\[\]]+)", d)
            if not mm or mm.group(1) not in ESZ:
                ts = None
                break
            ts.add(mm.group(1))
            for v in mm.group(2).split(","):
                k = 1
                for dim in re.findall(r"\[([^\]]+)\]", v):
                    k *= int(dim, 0)
                n += k
        if ts and len(ts) == 1:
            out[m.group(2)] = (ts.pop(), n)
    return out


def init_owner_text(own, names, labels, kind):
    """The owner with its externs for `names` turned into definitions, or None."""
    import data_to_c
    text = (ROOT / own).read_text()
    # the owner's own one-type structs, for define() (restored afterwards)
    data_to_c.struct_scalar("")
    cache = data_to_c.struct_scalar.__defaults__[0]
    added = {k: v for k, v in local_structs(text).items() if k not in cache}
    cache.update(added)
    try:
        return _init_owner_text(own, names, labels, kind, text)
    finally:
        for k in added:
            cache.pop(k, None)


def _init_owner_text(own, names, labels, kind, text):
    import data_to_c
    const = kind == "rodata"
    defs, need, first = [], set(), None
    start = labels[names[0]][0][1]
    for k, n in enumerate(names):
        ms = [m for m in EXTERN.finditer(text) if m.group("name") == n]
        if len(ms) != 1:
            return None
        m = ms[0]
        decl = {n: {(m.group("type").split()[-1], m.group("ptr"), m.group("dim") is not None)}}
        lab = labels[n][0]
        # the owner's last object ends at its last string (gen_ninja.py's
        # trailing_fill trims the target there); inside, as splat closes it
        trim = lab[3] if k < len(names) - 1 else True
        items = lab[2]
        num = lambda v: re.fullmatch(r"-?(0x[0-9A-Fa-f]+|\d+)", v)
        es = type_size(m.group("type").split()[-1], m.group("ptr"), text)
        if m.group("dim") is None and es and es % 4 == 0 and all(i[0] == "word" for i in items) \
                and 4 * len(items) > es and all(num(i[1]) and int(i[1], 0) == 0 for i in items[es // 4:]):
            items = items[:es // 4]     # one object of the type: the rest is padding
        if k == len(names) - 1 and any(i[0] == "asciz" for i in items):
            # what trails the owner's last string (empty strings, zero
            # bytes and halfwords) is padding: the next unit's alignment
            zero = lambda i: (i[0] == "asciz" and i[1] in ('""', "")) or \
                (i[0] in ("byte", "short") and int(i[1], 0) == 0)
            while len(items) > 1 and zero(items[-1]):
                items = items[:-1]
        d = data_to_c.define(n, items, decl, const, need, trim)
        base = m.group("type").split()[-1]
        if d is None or not re.match(rf"(const )?{re.escape(base)}\b", d):
            # a struct of mixed members: a brace-elided initialiser
            # (tools/split_data.py's layout of the owner's typedef)
            import split_data
            quals = "const" if const else ""
            d = None if m.group("ptr") else split_data.struct_init(n, base, m.group("dim") is not None, quals,
                                                                   items, text, need)
            if d is None:
                return None
        size = len(data_to_c.obj_bytes(items, trim)[0])
        defs.append([d, natural(size), min(natural(size), lab[1] & -lab[1], start & -start)])
        first = m.start() if first is None else min(first, m.start())
    defs[0][2] = max(x[2] for x in defs)
    out = []
    for d, nat, want in defs:
        if want != nat:
            d = d.replace(" = ", f" __attribute__((aligned({want}))) = ", 1)
        out.append(d)
    for n in names:
        m = next(m for m in EXTERN.finditer(text) if m.group("name") == n)
        text = text[:m.start()] + text[m.end():]
        if m.start() < first:
            first -= m.end() - m.start()
    ext = []
    for s_ in sorted(need):
        if not re.search(rf"\b{s_}\b", text):
            ext.append(f"void {s_}(void);" if is_func(s_) else f"extern u8 {s_}[];")
    block = "\n".join(ext + [f"#pragma explicit_zero_data on"] + out) + "\n"
    return text[:first] + block + text[first:]


def main_init(kind):
    import subprocess
    import tempfile
    import data_to_c
    runs, sz, labels, unit_of = plan_init(kind)
    only = [a for a in sys.argv[1:] if a.startswith("src/")]
    if only:
        runs = [r for r in runs if r[0] in only]
    if "--limit" in sys.argv:
        runs = runs[:int(sys.argv[sys.argv.index("--limit") + 1])]
    passing = []
    tmp = Path(tempfile.mkdtemp(dir=ROOT / "build"))
    for own, names in runs:
        t = init_owner_text(own, names, labels, kind)
        if t is None:
            print(f"{own}: type does not fit, stays")
            continue
        p = tmp / Path(own).name
        p.write_text(t)
        r = subprocess.run([str(ROOT / ".venv/bin/python"), "tools/match.py", "diff", str(p)],
                           capture_output=True, text=True, cwd=ROOT).stdout
        if re.search(r"differ|rror", r) or "MATCH" not in r:
            print(f"{own}: code changes (folding), stays")
            continue
        print(f"{own}: {', '.join(names)} ({sum(sz[n][1] for n in names):#x} bytes)")
        passing.append((own, names, t))
    print(f"{len(passing)} of {len(runs)} owners move", file=sys.stderr)
    if "--apply" not in sys.argv:
        return
    moved = set()
    for own, names, t in passing:
        (ROOT / own).write_text(t)
        moved |= set(names)
    # regenerate the touched data-only units without what moved
    for u in sorted({unit_of[n] for n in moved}):
        asm = labels[next(n for n in moved if unit_of[n] == u)][1]
        labs = data_to_c.parse(asm)
        first = unit_start(u)
        (ROOT / u).unlink()
        run = []
        for lab in labs + [None]:
            if lab is None or lab[0] in moved:
                if run:
                    stem, text = data_to_c.unit_text(str(asm), run)
                    remainder_path(u, first, run[0][1]).write_text(text)
                run = []
            else:
                run.append(lab)


def main():
    kind = sys.argv[sys.argv.index("--section") + 1] if "--section" in sys.argv else "bss"
    if kind != "bss":
        return main_init(kind)
    chosen, sz, alias, units, lines = plan()
    only = [a for a in sys.argv[1:] if a.startswith("src/")]
    if only:
        chosen = [c for c in chosen if c[0] in only]
    if "--limit" in sys.argv:
        chosen = chosen[:int(sys.argv[sys.argv.index("--limit") + 1])]
    total = sum(sz[n][1] for _, ns in chosen for n in ns)
    for own, ns in chosen:
        print(f"{own}: {', '.join(ns)} ({sum(sz[n][1] for n in ns):#x} bytes)")
    print(f"{len(chosen)} owners, {sum(len(ns) for _, ns in chosen)} objects, {total:#x} bytes", file=sys.stderr)
    if "--apply" not in sys.argv:
        return
    moved = set()
    for own, ns in chosen:
        (ROOT / own).write_text(owner_text(own, ns, sz))
        moved |= set(ns)
    write_units(moved, sz, units, lines)
    regroup_aliases(sz)


if __name__ == "__main__":
    main()
